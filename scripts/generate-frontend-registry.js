#!/usr/bin/env node

/**
 * Generates Backend/utils/frontendAssetRegistry.js: a literal, inline
 * path.join(__dirname, ...) call for every file actually present in
 * frontend/build after each build. This is what makes the packaged exe
 * truly single-file again.
 *
 * Root cause this works around: pkg's `assets` glob config (package.json)
 * was found to silently drop files from the compiled snapshot with no
 * working config-level fix (confirmed via an isolated minimal reproduction
 * outside this project). pkg DOES have a second, separate, reliable
 * mechanism though: it statically scans every compiled .js file (anything
 * matched by pkg.scripts, i.e. Backend/**\/*.js) for literal, INLINE
 * path.join(__dirname, 'literal/relative/path') expressions and reliably
 * bundles whatever file each one resolves to - confirmed by the 8
 * PowerShell scripts that already had exactly this pattern somewhere
 * (fetchADObject.js, lockedOutUsersUtils.js, etc) and were never affected
 * by the assets-glob bug. Backend/utils/scriptRegistry.js already applies
 * this trick by hand for the fixed-name PowerShell scripts; frontend build
 * output can't be hand-written the same way because the filenames are
 * content-hashed and change every build, so this script (re)generates the
 * equivalent file fresh after each frontend build, always matching
 * whatever actually exists that time.
 *
 * Important: each entry below must be a literal path.join(__dirname, ...)
 * call written out directly, NOT built from an intermediate variable -
 * pkg's static scanner matches the AST shape textually and there's no
 * confirmation it traces through indirection.
 */

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const buildDir = path.join(root, 'frontend/build');
const outFile = path.join(root, 'Backend/utils/frontendAssetRegistry.js');

if (!fs.existsSync(buildDir)) {
    console.error('frontend/build not found - run the frontend build first.');
    process.exit(1);
}

function walk(dir) {
    let out = [];
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            out = out.concat(walk(full));
        } else {
            out.push(path.relative(buildDir, full));
        }
    }
    return out;
}

// Forward slashes in the generated source so it reads the same regardless of
// the OS that generated it - path.join() converts to the right separator at
// runtime on whatever OS actually runs it.
const relativeFiles = walk(buildDir).map((f) => f.split(path.sep).join('/'));

const lines = relativeFiles.map((rel) => {
    const segments = rel.split('/').map((s) => JSON.stringify(s));
    return `        path.join(__dirname, '../../frontend/build', ${segments.join(', ')}),`;
});

const content = `const path = require('path');

/**
 * GENERATED FILE - do not edit by hand. Regenerated by
 * scripts/generate-frontend-registry.js after every frontend build, from
 * whatever is actually in frontend/build at that time. See that script for
 * why this file exists (pkg's static-scan asset detection workaround).
 */
function registerFrontendAssets() {
    return [
${lines.join('\n')}
    ];
}

module.exports = { registerFrontendAssets };
`;

fs.writeFileSync(outFile, content, 'utf8');
console.log(`Frontend asset registry generated: ${relativeFiles.length} files -> Backend/utils/frontendAssetRegistry.js`);
